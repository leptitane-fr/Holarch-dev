/// The character named `name` (without `&` and `;`).
pub fn lookup(name: &str) -> Option<char> {
    let i = ENTITIES.binary_search_by(|(n, _)| (*n).cmp(name)).ok()?;
    char::from_u32(ENTITIES[i].1)
}
